<?php

declare(strict_types=1);

namespace LeibnizPsychology\PhpDocAiTlp\Tests\Tag;

use LeibnizPsychology\PhpDocAiTlp\Tag\AiTlpFactory;
use InvalidArgumentException;
use phpDocumentor\Reflection\DocBlock\Description;
use PHPUnit\Framework\TestCase;

class AiTlpFactoryTest extends TestCase
{
    public function testCreateWithLevelOnly(): void
    {
        $tag = AiTlpFactory::create('amber');
        $this->assertEquals('ai-tlp', $tag->getName());
        $this->assertEquals('amber', $tag->getLevel());
        $this->assertNull($tag->getDescription());
    }

    public function testCreateNormalizesFullLabel(): void
    {
        $this->assertSame('amber', AiTlpFactory::create('AI:AMBER')->getLevel());
    }

    public function testCreateRejectsMissingOrInvalidLevels(): void
    {
        foreach (['', 'blue'] as $level) {
            try {
                AiTlpFactory::create($level);
                $this->fail('Invalid levels must be rejected.');
            } catch (InvalidArgumentException $exception) {
                $this->assertStringContainsString('Invalid AI-TLP level:', $exception->getMessage());
            }
        }
    }

    public function testCreateWithLevelAndDescription(): void
    {
        // Mocking DescriptionFactory is complex, so we test the constructor or just the parsing part
        $tag = AiTlpFactory::create('amber This was generated by AI.');
        $this->assertEquals('amber', $tag->getLevel());
        // Note: Without DescriptionFactory, description remains null in create()
        // but it no longer crashes.
    }

    public function testConstructorWithDescription(): void
    {
        $description = new Description('Assisted');
        $tag = new AiTlpFactory('green', $description);
        $this->assertEquals('green', $tag->getLevel());
        $this->assertSame($description, $tag->getDescription());
    }

    public function testToString(): void
    {
        $tag = new AiTlpFactory('green', new Description('Assisted'));
        $this->assertEquals('green Assisted', (string) $tag);
    }
}
